"""Downloadable student reports (Markdown and PDF)."""

from __future__ import annotations

import logging
from datetime import date

from . import config as cfg
from .models import Assessment
from .recommendations import build_timeline

logger = logging.getLogger(__name__)


class ReportError(RuntimeError):
    """Raised when a report cannot be generated."""


def build_markdown_report(a: Assessment, hours_per_week: int = 10) -> str:
    """Return a self-contained Markdown report for the assessment."""
    r, p = a.result, a.profile
    lines: list[str] = [
        f"# Internship Readiness Report: {p.name}",
        "",
        f"*Generated {date.today().isoformat()} | Target role: **{a.role}***",
        "",
        f"## Overall score: {r.total:.1f} / 100 ({r.level})",
        "",
        f"Estimated score after completing the top actions: **{a.potential_score:.1f}**",
        "",
        "## Profile snapshot",
        "",
        f"- Major: {p.major}",
        f"- CGPA: {p.cgpa:.2f} / {cfg.CGPA_MAX:.0f}",
        f"- Projects: {p.projects} | Internships: {p.internships} | Certifications: {p.certifications}",
        f"- Communication: {p.communication_score:.0f}/100 | Aptitude: {p.aptitude_score:.0f}/100",
        "",
        "## Score breakdown",
        "",
        "| Component | Weight | Points | Why |",
        "|---|---:|---:|---|",
    ]
    for c in r.components:
        lines.append(f"| {c.name} | {c.weight:.0f} | {c.points:.1f} | {c.detail} |")

    lines += [
        "",
        "## Skill gap analysis",
        "",
        f"- **Matched required:** {', '.join(r.matched_required) or 'none'}",
        f"- **Missing required:** {', '.join(r.missing_required) or 'none'}",
        f"- **Matched preferred:** {', '.join(r.matched_preferred) or 'none'}",
        f"- **Missing preferred:** {', '.join(r.missing_preferred) or 'none'}",
        "",
        "## Key insights",
        "",
    ]
    lines += [f"- {i.replace('**', '')}" for i in a.insights]

    lines += ["", "## Personalised action plan", ""]
    if not a.actions:
        lines.append("No gaps found. Keep polishing your portfolio and practising interviews.")
    for idx, act in enumerate(a.actions, 1):
        lines.append(f"### {idx}. {act.title}  [{act.priority}]")
        lines.append(f"*Impact: +{act.impact_points:.1f} pts | Effort: ~{act.effort_hours} h*")
        lines.append("")
        lines += [f"{n}. {s}" for n, s in enumerate(act.steps, 1)]
        if act.project_idea:
            lines.append(f"\n**Mini-project:** {act.project_idea}")
        lines.append("")

    timeline = build_timeline(a.actions, hours_per_week)
    if timeline:
        lines += [f"## Suggested timeline ({hours_per_week} h/week)", "", "| # | Action | Hours | Weeks | Impact |", "|---:|---|---:|---|---:|"]
        for row in timeline:
            lines.append(f"| {row['Order']} | {row['Action']} | {row['Hours']} | {row['Weeks']} | {row['Score impact']} |")

    lines += ["", "## Role fit", "", "| Role | Score |", "|---|---:|"]
    lines += [f"| {k} | {v:.1f} |" for k, v in sorted(a.role_scores.items(), key=lambda kv: -kv[1])]
    lines += ["", "---", "*Generated by the AI Internship Readiness Checker. Scores are guidance, not a guarantee.*", ""]
    return "\n".join(lines)


def _latin1(text: str) -> str:
    """Core PDF fonts only support latin-1; replace everything else safely."""
    table = {"\u2013": "-", "\u2014": "-", "\u2022": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2192": "->"}
    for src, dst in table.items():
        text = text.replace(src, dst)
    return text.replace("**", "").encode("latin-1", "replace").decode("latin-1")


def build_pdf_report(a: Assessment, hours_per_week: int = 10) -> bytes:
    """Render the report as a PDF (requires ``fpdf2``).

    Raises:
        ReportError: if fpdf2 is not installed or rendering fails.
    """
    try:
        from fpdf import FPDF
    except ImportError as exc:
        raise ReportError("PDF export needs `fpdf2` (pip install fpdf2). Use the Markdown download instead.") from exc

    r, p = a.result, a.profile
    try:
        pdf = FPDF(format="A4")
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        def h1(text: str) -> None:
            pdf.set_font("Helvetica", "B", 18)
            pdf.cell(0, 10, _latin1(text), new_x="LMARGIN", new_y="NEXT")

        def h2(text: str) -> None:
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 13)
            pdf.set_text_color(30, 64, 175)
            pdf.cell(0, 8, _latin1(text), new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(0, 0, 0)

        def para(text: str, size: int = 10, bold: bool = False, indent: float = 0) -> None:
            pdf.set_font("Helvetica", "B" if bold else "", size)
            pdf.set_x(pdf.l_margin + indent)
            pdf.multi_cell(0, 5.5, _latin1(text), new_x="LMARGIN", new_y="NEXT")

        h1("Internship Readiness Report")
        para(f"{p.name} | {p.major} | Target role: {a.role} | {date.today().isoformat()}", 10)
        pdf.ln(2)

        color = {cfg.LEVEL_READY: (22, 163, 74), cfg.LEVEL_ALMOST: (217, 119, 6)}.get(r.level, (220, 38, 38))
        pdf.set_font("Helvetica", "B", 26)
        pdf.set_text_color(*color)
        pdf.cell(0, 14, f"{r.total:.1f} / 100  -  {_latin1(r.level)}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(0, 0, 0)
        para(f"Estimated score after completing the top actions: {a.potential_score:.1f}", 10)

        h2("Score breakdown")
        for c in r.components:
            y = pdf.get_y()
            pdf.set_font("Helvetica", "", 10)
            pdf.cell(42, 6, _latin1(c.name))
            pdf.set_fill_color(226, 232, 240)
            pdf.rect(pdf.get_x(), y + 1, 90, 4, style="F")
            pdf.set_fill_color(*color)
            pdf.rect(pdf.get_x(), y + 1, max(0.5, 90 * c.fraction), 4, style="F")
            pdf.set_x(pdf.get_x() + 94)
            pdf.cell(0, 6, f"{c.points:.1f} / {c.weight:.0f}", new_x="LMARGIN", new_y="NEXT")

        h2("Skill gaps")
        para("Matched required: " + (", ".join(r.matched_required) or "none"))
        para("Missing required: " + (", ".join(r.missing_required) or "none"), bold=True)
        para("Missing preferred: " + (", ".join(r.missing_preferred) or "none"))

        h2("Key insights")
        for ins in a.insights:
            para("- " + ins, indent=2)

        h2("Personalised action plan")
        if not a.actions:
            para("No gaps found. Keep polishing your portfolio and practising interviews.")
        for idx, act in enumerate(a.actions[:10], 1):
            para(f"{idx}. {act.title} [{act.priority}]  +{act.impact_points:.1f} pts, ~{act.effort_hours} h", 10, bold=True)
            for n, step in enumerate(act.steps, 1):
                para(f"{n}) {step}", 9, indent=6)
            if act.project_idea:
                para(f"Mini-project: {act.project_idea}", 9, indent=6)
            pdf.ln(1)

        timeline = build_timeline(a.actions, hours_per_week)
        if timeline:
            h2(f"Suggested timeline ({hours_per_week} h/week)")
            for row in timeline:
                para(f"Week {row['Weeks']}: {row['Action']} ({row['Hours']} h, {row['Score impact']} pts)", 9, indent=2)

        pdf.ln(4)
        para("Scores are guidance, not a guarantee. Generated by the AI Internship Readiness Checker.", 8)
        return bytes(pdf.output())
    except Exception as exc:  # noqa: BLE001 - surface a friendly error to the UI
        logger.exception("PDF generation failed")
        raise ReportError(f"Could not build the PDF: {exc}") from exc
